import { Near } from "near-kit";
import { mainnetPayoutChecker, resolveAttribution, withByline, type PayoutChecker } from "./attribution.js";
import { assertValidCode, bylineMemo } from "./names.js";
import { OneClick, type OneClickToken, type QuoteRequest, type QuoteResponse, type StatusResponse, type SwapType } from "./oneclick.js";
import { Registry } from "./registry.js";
import { nearConfig, type Attribution, type BylineEvent, type NetworkId, type Recorder } from "./types.js";

/** NEP-145 registration for a fresh receiver. Enough for every common NEP-141 token. */
const FT_STORAGE_DEPOSIT = "0.00125 NEAR";
/**
 * Lean gas so a small (sponsored) account can still act: a call reserves its prepaid gas at a
 * pessimistic price until it settles. storage_deposit + ft_transfer = 25 Tgas.
 */
const GAS_STORAGE = "10 Tgas";
const GAS_FT_TRANSFER = "15 Tgas";

export interface BylineOptions {
  /** The agent's byline code, e.g. "k7m2x9qa" (generated by the registry). */
  code: string;
  /** Where the registry lives. Default "mainnet". 1Click swaps always settle on mainnet. */
  network?: NetworkId;
  /** Defaults to byline.near / byline.testnet. */
  registryId?: string;
  /** A near-kit instance that signs as the agent. Or pass accountId + privateKey. */
  near?: Near;
  /** The agent's account. Defaults to the byline's own account `<code>.<registry>` if it exists. */
  accountId?: string;
  privateKey?: string;
  /** 1Click partner JWT. Optional. */
  oneClickJwt?: string;
  oneClick?: OneClick;
  payoutChecker?: PayoutChecker;
  /** Called for every quote, deposit, transfer and status the SDK sees. */
  recorder?: Recorder;
}

export interface SwapInput {
  /** Origin token: an assetId (`nep141:wrap.near`) or a symbol on NEAR (`USDC`). */
  from: string;
  /** Destination token: an assetId or a symbol on `toChain`. */
  to: string;
  /** Amount in human units ("1.5"), or pass `amountRaw` in the token's smallest unit. */
  amount?: string;
  amountRaw?: string;
  /** Default "near". */
  toChain?: string;
  /** Who receives the output. Defaults to the agent's account. */
  recipient?: string;
  /** Where refunds go. Defaults to the agent's account. */
  refundTo?: string;
  /** Default 100 (1%). */
  slippageBps?: number;
  /** Default EXACT_INPUT. */
  swapType?: SwapType;
}

export interface QuoteResult {
  dry: boolean;
  request: QuoteRequest;
  response: QuoteResponse;
  attribution: Attribution;
  /**
   * The builder's share as 1Click actually charges it, read from the echoed request.
   * 1Click splits app fees with its own fee, so this is usually less than `fee_bps`.
   */
  builderFeeBps: number;
}

export interface SwapResult extends QuoteResult {
  /** False when called without `{ live: true }`: only a dry preview was made. */
  executed: boolean;
  depositAddress?: string;
  txHash?: string;
}

export interface TransferInput {
  /** NEP-141 token contract, e.g. "usdc.fakes.testnet" or "wrap.near". */
  token: string;
  receiverId: string;
  /** Amount in the token's smallest unit. */
  amountRaw: string;
  /** Free text after the code in the memo, e.g. an invoice id. */
  note?: string;
}

/** Converts "1.5" with 6 decimals to "1500000". */
export function toRawAmount(amount: string, decimals: number): string {
  if (!/^\d+(\.\d+)?$/.test(amount)) throw new Error(`Invalid amount "${amount}"`);
  const [whole, frac = ""] = amount.split(".");
  if (frac.length > decimals) throw new Error(`"${amount}" has more than ${decimals} decimals`);
  return (BigInt(whole!) * 10n ** BigInt(decimals) + BigInt(frac.padEnd(decimals, "0") || "0")).toString();
}

/**
 * Before any money moves: the quote 1Click returned must be for what we asked (same amount in for
 * EXACT_INPUT, same recipient, refund address and referral). Throws on any mismatch.
 */
export function assertQuoteMatches(request: QuoteRequest, response: QuoteResponse): void {
  const echoed = response.quoteRequest;
  const problems: string[] = [];
  if (echoed.recipient !== request.recipient) problems.push(`recipient ${echoed.recipient} ≠ ${request.recipient}`);
  if (echoed.refundTo !== request.refundTo) problems.push(`refundTo ${echoed.refundTo} ≠ ${request.refundTo}`);
  if (request.referral && echoed.referral !== request.referral) problems.push(`referral ${echoed.referral} ≠ ${request.referral}`);
  if (echoed.originAsset !== request.originAsset) problems.push(`originAsset ${echoed.originAsset} ≠ ${request.originAsset}`);
  if (request.swapType === "EXACT_INPUT" && response.quote.amountIn !== request.amount) {
    problems.push(`amountIn ${response.quote.amountIn} ≠ requested ${request.amount}`);
  }
  if (problems.length) throw new Error(`1Click's quote doesn't match the request; nothing was sent (${problems.join("; ")})`);
}

/** Sum of the fees 1Click will pay to this byline's payout(s), from the echoed quote request. */
export function builderShare(attribution: Pick<Attribution, "appFees">, response: QuoteResponse): number {
  const payouts = new Set(attribution.appFees.map((f) => f.recipient));
  return (response.quoteRequest.appFees ?? []).filter((f) => payouts.has(f.recipient)).reduce((n, f) => n + f.fee, 0);
}

function txHashOf(outcome: unknown): string {
  const o = outcome as { transaction_outcome?: { id?: string }; transaction?: { hash?: string } };
  const hash = o.transaction_outcome?.id ?? o.transaction?.hash;
  if (!hash) throw new Error("Transaction sent but no hash in the outcome");
  return hash;
}

/**
 * One agent's byline. Attaches its attribution to 1Click swaps, adds `byline:<code>`
 * to token transfers, and links accounts. Quotes and swaps are dry unless `{ live: true }`.
 */
export class Byline {
  readonly code: string;
  readonly network: NetworkId;
  readonly registry: Registry;
  readonly oneClick: OneClick;
  readonly near: Near;
  private accountId?: string;
  private readonly checker: PayoutChecker;
  private readonly recorder?: Recorder;
  private attributionCache?: Promise<Attribution>;

  constructor(opts: BylineOptions) {
    assertValidCode(opts.code);
    this.code = opts.code;
    this.network = opts.network ?? "mainnet";
    this.near =
      opts.near ??
      new Near({
        ...nearConfig(this.network),
        ...(opts.privateKey ? { privateKey: opts.privateKey as `ed25519:${string}` } : {}),
        ...(opts.accountId ? { defaultSignerId: opts.accountId } : {}),
      });
    this.registry = new Registry({ network: this.network, contractId: opts.registryId, near: this.near });
    this.oneClick = opts.oneClick ?? new OneClick({ jwt: opts.oneClickJwt });
    this.accountId = opts.accountId;
    this.checker = opts.payoutChecker ?? mainnetPayoutChecker();
    this.recorder = opts.recorder;
  }

  /** The account the agent signs with. */
  async account(): Promise<string> {
    if (this.accountId) return this.accountId;
    const record = await this.registry.getByline(this.code);
    if (!record) throw new Error(`No byline "${this.code}" in ${this.registry.contractId}`);
    if (!record.account) throw new Error(`Byline "${this.code}" has no account yet: pass accountId`);
    this.accountId = record.account;
    return record.account;
  }

  /** Referral and fees as the SDK will attach them. Cached; call `refresh()` after an update. */
  attribution(): Promise<Attribution> {
    this.attributionCache ??= resolveAttribution(this.registry, this.code, this.checker).catch((e) => {
      this.attributionCache = undefined;
      throw e;
    });
    return this.attributionCache;
  }

  refresh(): void {
    this.attributionCache = undefined;
  }

  /** Add this byline's referral and fees to any 1Click quote request you built yourself. */
  async attach<T extends Partial<QuoteRequest>>(request: T) {
    const a = await this.attribution();
    return withByline(request, a);
  }

  /** A 1Click quote credited to this byline. Dry unless `{ live: true }` (live returns a deposit address). */
  async quote(input: SwapInput, { live = false }: { live?: boolean } = {}): Promise<QuoteResult> {
    const [attribution, origin, destination] = await Promise.all([
      this.attribution(),
      this.oneClick.token(input.from, "near"),
      this.oneClick.token(input.to, input.toChain ?? "near"),
    ]);
    const amount = this.rawAmount(input, origin);
    const self = input.recipient && input.refundTo ? undefined : await this.account();
    const baseRequest: QuoteRequest = {
      dry: !live,
      swapType: input.swapType ?? "EXACT_INPUT",
      slippageTolerance: input.slippageBps ?? 100,
      originAsset: origin.assetId,
      depositType: "ORIGIN_CHAIN",
      destinationAsset: destination.assetId,
      amount,
      recipient: input.recipient ?? self!,
      recipientType: "DESTINATION_CHAIN",
      refundTo: input.refundTo ?? self!,
      refundType: "ORIGIN_CHAIN",
      deadline: new Date(Date.now() + 10 * 60_000).toISOString(),
    };
    const request = withByline(baseRequest, attribution);
    const response = await this.oneClick.quote(request);
    const builderFeeBps = builderShare(attribution, response);
    await this.record({
      kind: "quote",
      at: new Date().toISOString(),
      code: this.code,
      dry: request.dry,
      correlationId: response.correlationId,
      depositAddress: response.quote.depositAddress,
      originAsset: request.originAsset,
      destinationAsset: request.destinationAsset,
      amountIn: response.quote.amountIn,
      amountOut: response.quote.amountOut,
      amountInUsd: response.quote.amountInUsd,
      referral: request.referral,
      appFees: request.appFees ?? [],
      builderFeeBps,
      warnings: attribution.warnings,
    });
    return { dry: request.dry, request, response, attribution, builderFeeBps };
  }

  /**
   * Swap through 1Click, credited to this byline.
   * Without `{ live: true }` this only previews (dry quote) and moves nothing.
   * Live: commits a quote, sends the origin token to the deposit address with memo `byline:<code>`,
   * and tells 1Click about the deposit. NEAR mainnet only, origin token on NEAR.
   */
  async swap(input: SwapInput, { live = false }: { live?: boolean } = {}): Promise<SwapResult> {
    if (!live) return { ...(await this.quote(input)), executed: false };
    if (this.network !== "mainnet") {
      throw new Error("Live swaps settle on NEAR mainnet; this Byline is on testnet. Use a dry quote instead.");
    }
    const origin = await this.oneClick.token(input.from, "near");
    const tokenContract = origin.assetId.startsWith("nep141:") ? origin.assetId.slice("nep141:".length) : null;
    if (origin.blockchain !== "near" || !tokenContract) {
      throw new Error(`Live swaps deposit from NEAR; ${input.from} is on ${origin.blockchain}`);
    }
    const quoted = await this.quote(input, { live: true });
    const depositAddress = quoted.response.quote.depositAddress;
    if (!depositAddress) throw new Error("1Click returned no deposit address");
    assertQuoteMatches(quoted.request, quoted.response);
    const amount = quoted.response.quote.amountIn;

    const sender = await this.account();
    const txHash = await this.sendFt(sender, tokenContract, depositAddress, amount, bylineMemo(this.code));
    await this.oneClick.submitDeposit({ txHash, depositAddress, nearSenderAccount: sender }).catch(() => {
      /* optional: 1Click also detects the deposit on its own */
    });
    await this.record({
      kind: "deposit",
      at: new Date().toISOString(),
      code: this.code,
      depositAddress,
      txHash,
      sender,
      token: tokenContract,
      amount,
    });
    return { ...quoted, executed: true, depositAddress, txHash };
  }

  /** Swap status from 1Click; recorded so the indexer sees how the swap ended. */
  async status(depositAddress: string): Promise<StatusResponse> {
    const s = await this.oneClick.status(depositAddress);
    await this.record({ kind: "status", at: new Date().toISOString(), code: this.code, depositAddress, status: s.status });
    return s;
  }

  /** NEP-141 transfer with memo `byline:<code>[ note]`, signed by the agent. Works on testnet and mainnet. */
  async transfer(input: TransferInput): Promise<{ txHash: string; memo: string }> {
    const memo = bylineMemo(this.code, input.note);
    const sender = await this.account();
    const txHash = await this.sendFt(sender, input.token, input.receiverId, input.amountRaw, memo);
    await this.record({
      kind: "transfer",
      at: new Date().toISOString(),
      code: this.code,
      txHash,
      sender,
      token: input.token,
      receiver: input.receiverId,
      amount: input.amountRaw,
      memo,
    });
    return { txHash, memo };
  }

  /** Link the agent's account to this byline. The builder must have invited it first. */
  async link(): Promise<void> {
    const accountId = await this.account();
    const current = await this.registry.getBylineForAccount(accountId);
    if (current === this.code) return;
    if (current) throw new Error(`${accountId} is already linked to byline "${current}"; unlink it first`);
    await new Registry({
      network: this.network,
      contractId: this.registry.contractId,
      near: this.near,
      signerId: accountId,
    }).linkAccount(this.code);
  }

  private rawAmount(input: SwapInput, token: OneClickToken): string {
    if (input.amountRaw) return input.amountRaw;
    if (input.amount) return toRawAmount(input.amount, token.decimals);
    throw new Error("Pass amount or amountRaw");
  }

  private async sendFt(sender: string, token: string, receiver: string, amount: string, memo: string): Promise<string> {
    const registered = await this.near.view(token, "storage_balance_of", { account_id: receiver });
    let tx = this.near.transaction(sender);
    if (!registered) {
      tx = tx.functionCall(
        token,
        "storage_deposit",
        { account_id: receiver, registration_only: true },
        { gas: GAS_STORAGE, attachedDeposit: FT_STORAGE_DEPOSIT },
      );
    }
    tx = tx.functionCall(
      token,
      "ft_transfer",
      { receiver_id: receiver, amount, memo },
      { gas: GAS_FT_TRANSFER, attachedDeposit: "1 yocto" },
    );
    return txHashOf(await tx.send({ waitUntil: "FINAL" }));
  }

  private async record(event: BylineEvent): Promise<void> {
    if (!this.recorder) return;
    try {
      await this.recorder(event);
    } catch {
      /* recording must never break the agent */
    }
  }
}
