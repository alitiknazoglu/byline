/** Byline codes: the same rules the registry contract enforces (contract/RULES.md). */

/** Lowercase base32 without i, l, o, u: valid in NEAR account ids and 1Click referrals, hard to misread. */
export const CODE_ALPHABET = "0123456789abcdefghjkmnpqrstvwxyz";
export const CODE_LEN = 8;
export const CODE_PATTERN = /^[0-9a-hjkmnp-tv-z]{8}$/;

export const DEFAULT_FEE_BPS = 40;
export const MAX_FEE_BPS = 100;

/** Prefix that token transfers carry in their memo to credit a byline. */
export const MEMO_PREFIX = "byline:";

export function isValidCode(code: string): boolean {
  return CODE_PATTERN.test(code);
}

export function assertValidCode(code: string): void {
  if (!isValidCode(code)) {
    throw new Error(`Invalid byline code "${code}": codes are ${CODE_LEN} characters from ${CODE_ALPHABET}, generated by the registry`);
  }
}

/** `byline:<code>`, the memo for token transfers. */
export function bylineMemo(code: string, note?: string): string {
  assertValidCode(code);
  return note ? `${MEMO_PREFIX}${code} ${note}` : `${MEMO_PREFIX}${code}`;
}

/** Reads the byline code out of a transfer memo, or returns null. */
export function parseBylineMemo(memo: string | null | undefined): string | null {
  if (!memo || !memo.startsWith(MEMO_PREFIX)) return null;
  const code = memo.slice(MEMO_PREFIX.length).split(/\s/, 1)[0] ?? "";
  return isValidCode(code) ? code : null;
}

/** `<code>.<registry>`: the agent's own account. */
export function agentAccountId(code: string, registryId: string): string {
  assertValidCode(code);
  return `${code}.${registryId}`;
}

/** The first 8 base32 characters of sha256(seed), exactly as the contract derives codes. */
export async function codeFromSeed(seed: Uint8Array): Promise<string> {
  const h = new Uint8Array(await globalThis.crypto.subtle.digest("SHA-256", seed as BufferSource));
  let bits = 0n;
  for (const b of h.subarray(0, 5)) bits = (bits << 8n) | BigInt(b);
  let out = "";
  for (let i = 0; i < CODE_LEN; i++) out += CODE_ALPHABET[Number((bits >> BigInt(35 - 5 * i)) & 31n)];
  return out;
}

/**
 * A hint: the code a gasless registration with this ed25519 key will get if nobody holds it yet.
 * If it's taken, the registry picks an unpredictable fallback. Never send funds to an account
 * derived from this alone: confirm with `registry.getBylineForKey(publicKey)` first.
 */
export async function codeForKey(publicKeyBytes: Uint8Array): Promise<string> {
  const prefix = new TextEncoder().encode("byline:v2:");
  const seed = new Uint8Array(prefix.length + publicKeyBytes.length);
  seed.set(prefix);
  seed.set(publicKeyBytes, prefix.length);
  return codeFromSeed(seed);
}
